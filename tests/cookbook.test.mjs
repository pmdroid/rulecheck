function run(bin, args, { cwd, input, status = 0 } = {}) {
  const result = spawnSync(bin, args, { cwd, input, encoding: "utf8", timeout: 20_000 });
  assert.ifError(result.error);
  assert.equal(result.status, status, `${bin} ${args.join(" ")}\n${result.stderr}\n${result.stdout}`);
  return result;
}

for (const [name, { clean, bad, finding, args: flags }] of Object.entries(recipes)) {
  test(name, (t) => {
    const cwd = mkdtempSync(join(tmpdir(), "rulecheck-recipe-"));
    t.after(() => rmSync(cwd, { recursive: true, force: true }));
    const git = (...args) => run("git", args, { cwd }).stdout.trimEnd();
    const write = (files) => {
      for (const [path, data] of Object.entries(files)) {
        const file = join(cwd, path);
        mkdirSync(dirname(file), { recursive: true });
        writeFileSync(file, data);
      }
    };
    git("init", "-q");
    const rulePath = join(cwd, ".rulecheck/rules", `${name}.rule.ts`);
    mkdirSync(dirname(rulePath), { recursive: true });
    copyFileSync(join(root, "docs/examples/rules", `${name}.rule.ts`), rulePath);
    // Set files are read from the checkout's .rulecheck/sets, like rules.
    if (name === "exclusion-sets") {
      mkdirSync(join(cwd, ".rulecheck/sets"));
      for (const set of ["generated", "third-party"]) {
        copyFileSync(join(root, "docs/examples/sets", `${set}.set.ts`), join(cwd, ".rulecheck/sets", `${set}.set.ts`));
      }
    }
    const input = run(process.execPath, [join(root, "tools/build.mjs"), "--root", cwd], { cwd }).stdout;
    run(evaluator, ["validate"], { input, cwd });
    run(evaluator, ["test", "--strict-fixtures"], { input, cwd });
    const scan = ({ policy = input, sha, expected = "" } = {}) => {
      const args = ["check", "--root", cwd, ...flags, ...(sha ? ["--commit", sha] : [])];
      const actual = run(evaluator, args, { input: policy, cwd, status: expected ? 1 : 0 });
      assert.equal(actual.stdout.trimEnd(), expected);
      assert.equal(actual.stderr, "");
    };
    write(clean);
    git("add", "-f", "--", ".");
    if (name === "rule-sources") {
      const unexcluded = JSON.parse(input);
      for (const rule of unexcluded.rules) delete rule.exclude;
      const policy = JSON.stringify(unexcluded);
      git("-c", "user.name=Rulecheck", "-c", "user.email=rulecheck@example.invalid",
        "-c", "commit.gpgsign=false", "commit", "-qm", "Add rule");
      const sha = git("rev-parse", "HEAD");
      const expected = ".rulecheck/rules/rule-sources.rule.ts:8:39: [source/no-debugger] Remove the debugger statement.";
      scan({ policy, expected });
      scan({ policy, expected, sha });
      scan({ sha });
    }
    scan();
    write(bad);
    git("add", "-f", "--", ".");
    scan({ expected: finding });
    if (name === "all-matches" || name.startsWith("structured")) {
      // Without the flag the same file reports its first match only, and the
      // exact commit reports the same matches as the working tree.
      const first = run(evaluator, ["check", "--root", cwd], { input, cwd, status: 1 });
      assert.equal(first.stdout.trimEnd(), finding.split("\n")[0]);
      git("-c", "user.name=Rulecheck", "-c", "user.email=rulecheck@example.invalid",
        "-c", "commit.gpgsign=false", "commit", "-qm", "Add markers");
      scan({ expected: finding, sha: git("rev-parse", "HEAD") });
    }
    if (name === "path-anchors") {
      // The service moves: the stale rule cannot judge in either mode.
      git("rm", "-q", "--cached", "services/billing/config/dev.local.toml");
      git("mv", "services/billing", "services/payments");
      git("-c", "user.name=Rulecheck", "-c", "user.email=rulecheck@example.invalid",
        "-c", "commit.gpgsign=false", "commit", "-qm", "Move the service");
      const missing = "[config/no-service-overrides] missing anchor: no file matches the rule's anchors, "
        + "so the area it guards moved or vanished and an absent forbidden path proves nothing; "
        + "restore the anchor or update anchors and paths together\n"
        + "rulecheck: one or more forbidden-path rules found none of their anchors\n";
      for (const sha of [null, git("rev-parse", "HEAD")]) {
        const args = ["check", "--root", cwd, ...(sha ? ["--commit", sha] : [])];
        const moved = run(evaluator, args, { input, cwd, status: 2 });
        assert.equal(moved.stdout, "");
        assert.equal(moved.stderr, missing);
      }
    }
    if (name.startsWith("consistency-")) {
      // The exact commit judges the same inventory the same way.
      git("-c", "user.name=Rulecheck", "-c", "user.email=rulecheck@example.invalid",
        "-c", "commit.gpgsign=false", "commit", "-qm", "Break consistency");
      scan({ expected: finding, sha: git("rev-parse", "HEAD") });
    }
    if (name === "requires") {
      // The exact commit judges the same bytes the same way, and restoring the
      // requirement clears the finding.
      git("-c", "user.name=Rulecheck", "-c", "user.email=rulecheck@example.invalid",
        "-c", "commit.gpgsign=false", "commit", "-qm", "Drop clearInterval");
      scan({ expected: finding, sha: git("rev-parse", "HEAD") });
      write(clean);
      scan();
    }
    if (name === "ignore-inside") {
      // The exact commit classifies the same bytes the same way. A file that
      // does not parse cannot be classified once the pattern matches in it.
      git("-c", "user.name=Rulecheck", "-c", "user.email=rulecheck@example.invalid",
        "-c", "commit.gpgsign=false", "commit", "-qm", "Call eval");
      scan({ expected: finding, sha: git("rev-parse", "HEAD") });
      write({ "src/run.ts": "// eval(code)\nexport const run = (;\n" });
      const broken = run(evaluator, ["check", "--root", cwd], { input, cwd, status: 2 });
      assert.equal(broken.stdout, "");
      assert.match(broken.stderr, /\[source\/no-eval\] src\/run\.ts: ignoreInside cannot classify the match: cannot parse as TypeScript near 2:/);
    }
    if (name === "scope") {
      write(clean);
      scan();
    }
  });
}

test("tag coverage report", (t) => {
  const cwd = mkdtempSync(join(tmpdir(), "rulecheck-coverage-"));
  t.after(() => rmSync(cwd, { recursive: true, force: true }));
  run("git", ["init", "-q"], { cwd });
  mkdirSync(join(cwd, ".rulecheck/rules"), { recursive: true });
  for (const name of ["tags", "literal"]) {
    copyFileSync(join(root, "docs/examples/rules", `${name}.rule.ts`), join(cwd, ".rulecheck/rules", `${name}.rule.ts`));
  }
  const input = run(process.execPath, [join(root, "tools/build.mjs"), "--root", cwd], { cwd }).stdout;
  const inventory = run(evaluator, ["list", "--format", "json"], { input, cwd }).stdout;
  const document = JSON.parse(inventory);
  assert.deepEqual(document.rules.map(({ id, tags }) => [id, tags]), [
    ["billing/no-float-amounts", ["adr/0007", "domain/billing"]],
    ["config/no-legacy-spelling", []],
  ]);
  assert.equal(run(evaluator, ["list"], { input, cwd }).stdout, "billing/no-float-amounts\nconfig/no-legacy-spelling\n");
  const coverage = join(root, "tools/coverage.mjs");
  const required = join(root, "docs/examples/coverage/required-tags.txt");
  const missing = run(process.execPath, [coverage, "--required", required], { input: inventory, cwd, status: 1 });
  assert.equal(missing.stdout, "covered adr/0007: billing/no-float-amounts\n"
    + "missing adr/0012: no rule has this tag\n"
    + "covered domain/billing: billing/no-float-amounts\n"
    + "untagged rules: config/no-legacy-spelling\n"
    + "2 of 3 required tags covered\n");
  const covered = run(process.execPath, [coverage, "--require", "domain/billing", "--format", "json"], { input: inventory, cwd });
  assert.deepEqual(JSON.parse(covered.stdout), {
    coverageVersion: 1,
    policySha256: document.policy.sha256,
    required: [{ tag: "domain/billing", rules: ["billing/no-float-amounts"] }],
    missing: [],
    untaggedRules: ["config/no-legacy-spelling"],
  });
  run(process.execPath, [coverage, "--require", "domain/billing"], { input: "[]", cwd, status: 2 });
});

